import { suggestQuerySchema } from "@fpp/core";
import { json, route, searchParams } from "@/lib/server/http";
import { clientIp, rateLimit } from "@/lib/server/rateLimit";
import { strongest } from "@/lib/server/queries";

export const dynamic = "force-dynamic";

/** Build My Slip: the same ranked, filtered selections — capped at `max`, never padded. */
export const GET = route(async (req) => {
  await rateLimit(`ip:${clientIp(req)}:read`, 120);
  const { max, ...q } = suggestQuerySchema.parse(searchParams(req));
  const res = await strongest({ ...q, limit: max ?? 5 });
  return json({ ...res, notices: [...res.notices, "Suggestions are generated by a statistical model. They are not guarantees."] });
});
